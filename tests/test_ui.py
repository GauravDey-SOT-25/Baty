import unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
class UITests(unittest.TestCase):
 def test_ui_handlers_are_external_to_match_csp(self):
  page=(ROOT/"frontend/index.html").read_text();script=(ROOT/"frontend/app.js").read_text();research=(ROOT/"frontend/research.js").read_text()
  self.assertIn('script src="/app.js"',page)
  self.assertNotIn("onclick=",page)
  self.assertIn('script src="/research.js"',page)
  self.assertIn('id="rtab-answers"', page)
  self.assertIn('id="rtab-findall"', page)
  self.assertIn('data-home-research="monitors"', page)
  self.assertIn('id="home" class="landing-home"', page)
  self.assertIn('/api/research/responses', research)
  self.assertIn('replaceChildren()', research)
  self.assertNotIn("innerHTML",research)
  self.assertIn("Do not paste private messages",page)
  self.assertIn('id="account" class="hidden"', page)
  self.assertIn("only future Learning assistant questions and answers", page)
  self.assertIn('id="cloud-sync" type="checkbox"', page)
  firebase = (ROOT / "frontend/firebase-app.js").read_text()
  self.assertIn("signInWithPopup", firebase)
  self.assertIn("saveAssistantExchange", firebase)
  self.assertIn("replaceChildren", firebase)
  self.assertNotIn("innerHTML", firebase)
  self.assertIn("12.19.0", firebase)
  self.assertIn('id="use-modal-model"', page)
  self.assertIn('id="trust"', page)
  self.assertIn('id="trust-check-tls" type="checkbox"', page)
  self.assertIn('id="trust-check-reputation" type="checkbox"', page)
  self.assertNotIn('id="trust-check-tls" type="checkbox" checked', page)
  self.assertNotIn('id="trust-check-reputation" type="checkbox" checked', page)
  self.assertIn('/trust.js', page)
  trust = (ROOT / "frontend/trust.js").read_text()
  self.assertNotIn("innerHTML", trust)
  self.assertIn("/api/trust/inspect", trust)
  self.assertIn("/api/modal/assistant", script)
  self.assertIn("getIdToken", script)
  self.assertIn("is sent to Modal", script)
  for endpoint in ("/api/message","/api/url","/api/assistant","/api/modal/assistant","/api/incidents"):
   self.assertIn(endpoint,script)

 def test_research_links_are_safe_and_csp_compliant(self):
  research = (ROOT / "frontend/research.js").read_text()
  self.assertNotIn("innerHTML", research)
  self.assertIn("noopener noreferrer", research)
  self.assertIn("_blank", research)
  self.assertIn("isSafeUrl", research)
  self.assertIn("replaceChildren", research)

if __name__=="__main__":unittest.main()
